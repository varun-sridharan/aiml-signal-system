"""Build static/tokens.css, the one stylesheet of design tokens every page loads, from design/system/tokens/.

    python scripts/build_tokens.py          # write static/tokens.css
    python scripts/build_tokens.py --check  # exit 1 if the committed file is not what the sources build

The kit's token files are the single source (design/system/readme.md); this concatenates them in the order the kit's own
styles.css imports them, plus the site additions. Variables only: the font @import is a <link> in templates/_head.html, and the kit's base.css (element
defaults for the reading page) lives in static/site.css under the Edition layout.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TOKENS = REPO / "design" / "system" / "tokens"
OUT = REPO / "static" / "tokens.css"
ORDER = ("colors.css", "site.css", "typography.css", "spacing.css")        # variables only; base.css is the Edition layout's element rules (static/site.css)

HEADER = ("/* GENERATED by scripts/build_tokens.py from design/system/tokens/. Do not edit: change the source and rebuild.\n"
          "   Colours, type and spacing as variables, for every AI/ML Signal page. */\n")


def build() -> str:
    parts = [HEADER]
    for name in ORDER:
        parts.append(f"\n/* ---- {name} ---- */\n" + (TOKENS / name).read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(parts)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("static/tokens.css is not what design/system/tokens/ builds; run python scripts/build_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
